  function buildLevel(n) {
    const index = n % grounds.length;
    const data = grounds[index].slice();
    const first = data.indexOf(SAND_TILE);
    const last2 = data.lastIndexOf(SAND_TILE);
    data[first] = START_TILE;
    data[last2] = FINISH_TILE;
    ground = data;
    collision = collisions[index % collisions.length];
    startTile = { x: first % MAP_WIDTH, y: Math.floor(first / MAP_WIDTH) };
    finishTile = { x: last2 % MAP_WIDTH, y: Math.floor(last2 / MAP_WIDTH) };
    mapDirty = true;
  }
  function isSea(col, row) {
    if (col < 0 || row < 0 || col >= MAP_WIDTH || row >= MAP_HEIGHT) return true;
    return !!collision[row * MAP_WIDTH + col];
  }
  function collides(x, y, width, height) {
    const r0 = Math.floor(y / TILE);
    const r1 = Math.floor((y + height) / TILE);
    const c0 = Math.floor(x / TILE);
    const c1 = Math.floor((x + width) / TILE);
    for (let r = r0; r <= r1; ++r) {
      for (let col = c0; col <= c1; ++col) {
        if (r >= 0 && r < MAP_HEIGHT && col >= 0 && col < MAP_WIDTH && collision[r * MAP_WIDTH + col]) {
          return true;
        }
      }
    }
    return false;
  }
  function resetPlayer() {
    player.x = TILE * startTile.x + TILE / 8;
    player.y = TILE * (startTile.y + 0.125);
  }
  function resetEnemies() {
    enemies.length = 0;
    const land = collision.reduce((sum, tile) => sum + (tile ? 0 : 1), 0);
    const count = Math.floor(land / 13);
    for (let i = 0; i < count; ++i) {
      let col, row, tries = 0;
      do {
        col = Math.floor(Math.random() * MAP_WIDTH);
        row = Math.floor(Math.random() * MAP_HEIGHT);
      } while (++tries < 1e3 && (isSea(col, row) || col === startTile.x || col === finishTile.x));
      if (tries >= 1e3) break;
      enemies.push({
        x: col * TILE + TILE / 8,
        y: row * TILE,
        width: SPRITE_SIZE,
        height: SPRITE_SIZE,
        dy: (Math.random() < 0.5 ? -0.5 : 0.5) * ((level + 1) / 3)
      });
    }
  }
