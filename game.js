  function renderMap() {
    const w = Math.round(SCREEN_WIDTH * k);
    const h = Math.round(SCREEN_HEIGHT * k);
    if (!mapCanvas) mapCanvas = document.createElement("canvas");
    mapCanvas.width = w;
    mapCanvas.height = h;
    const m = mapCanvas.getContext("2d");
    for (let row = 0; row < MAP_HEIGHT; ++row) {
      for (let col = 0; col < MAP_WIDTH; ++col) {
        const tile = tiles[ground[row * MAP_WIDTH + col]] || tiles[16];
        const x0 = Math.round(col * TILE * k);
        const y0 = Math.round(row * TILE * k);
        const x1 = Math.round((col + 1) * TILE * k);
        const y1 = Math.round((row + 1) * TILE * k);
        m.fillStyle = tile.bkcolor;
        m.fillRect(x0, y0, x1 - x0, y1 - y0);
        if (!tile.circles) continue;
        const s = (x1 - x0) / TILE;
        const sy = (y1 - y0) / TILE;
        m.save();
        m.beginPath();
        m.rect(x0, y0, x1 - x0, y1 - y0);
        m.clip();
        const cell = TILE / 8;
        const offset = cell / 2;
        const radiuses = [0.5, 1, 2, 4];
        for (const circle of tile.circles) {
          const cx = offset + (circle.x + 4) * cell;
          const cy = offset + (circle.y + 4) * cell;
          m.fillStyle = circle.color;
          m.beginPath();
          m.arc(x0 + cx * s, y0 + cy * sy, offset * radiuses[circle.radius] * s, 0, Math.PI * 2);
          m.fill();
        }
        m.restore();
      }
    }
    mapDirty = false;
  }
