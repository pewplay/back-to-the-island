  function zzfx(volume, randomness, frequency, length = 1, attack = 0.1, slide = 0, noise = 0, modulation = 0, modulationPhase = 0) {
    const sampleRate = 44100;
    const PI2 = Math.PI * 2;
    let f = frequency * PI2 / sampleRate;
    f *= 1 + randomness * (2 * Math.random() - 1);
    slide *= 1e3 * Math.PI / sampleRate ** 2;
    const samples = length > 0 ? sampleRate * (length > 10 ? 10 : length) | 0 : 1;
    attack *= samples;
    modulation *= PI2 / sampleRate;
    modulationPhase *= Math.PI;
    const data = new Float32Array(samples);
    let t = 0;
    let tm = 0;
    for (let i = 0; i < samples; ++i) {
      data[i] = volume * VOLUME * Math.cos(t * f * Math.cos(tm * modulation + modulationPhase)) * (i < attack ? i / attack : 1 - (i - attack) / (samples - attack));
      t += 1 + noise * (2 * Math.random() - 1);
      tm += 1 + noise * (2 * Math.random() - 1);
      f += slide;
    }
    const buffer = audioContext.createBuffer(1, samples, sampleRate);
    buffer.getChannelData(0).set(data);
    const source = audioContext.createBufferSource();
    source.buffer = buffer;
    source.connect(audioContext.destination);
    source.start();
  }
