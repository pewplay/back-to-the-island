  function drawText(plot, text2, x, y, scale, align = "left") {
    const str = String(text2).toUpperCase();
    const width = str.length * CHARACTER_WIDTH * scale;
    if (align === "center") x -= width / 2;
    else if (align === "right") x -= width;
    for (let i = 0; i < str.length; ++i) {
      const glyph = font[str.charCodeAt(i) - 32];
      if (!glyph) continue;
      for (let row = 0; row < CHARACTER_HEIGHT; ++row) {
        let mask = 8;
        for (let col = 0; col < CHARACTER_WIDTH; ++col, mask >>= 1) {
          if (glyph[row] & mask) {
            plot(x + (i * CHARACTER_WIDTH + col) * scale, y + row * scale, scale);
          }
        }
      }
    }
    return width;
  }

